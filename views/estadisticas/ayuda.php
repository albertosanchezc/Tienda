<div class="ayudas">

    <div class="ayuda-estadisticas">
        <h3>Platillos más pedidos:</h3>
        <ul>
            <li>Mantén un stock adecuado de ingredientes.</li>
            <li>Promueve estos platillos en el menú y mediante ofertas especiales.</li>
            <li>Considera aumentar ligeramente el precio si la demanda es alta.</li>
        </ul>
        <h3>Platillos menos pedidos:</h3>
        <ul>
            <li>Revisa los ingredientes, presentación y precio.</li>
            <li>Realiza encuestas para entender la baja popularidad.</li>
            <li>Considera retirar estos platillos o reintroducirlos con nuevas recetas.</li>
        </ul>
    </div>

    <div class="ayuda-estadisticas">
        <h3>Mesas con mayor variedad de pedidos:</h3>
        <ul>
            <li>Crea combos o menús especiales basados en patrones de pedidos.</li>
            <li>Ofrece incentivos como descuentos para grupos grandes.</li>
        </ul>
        <h3>Mesas con menor variedad de pedidos:</h3>
        <ul>
            <li>Ofrece sugerencias personalizadas para diversificar los pedidos.</li>
            <li>Capacita a los meseros para recomendar combinaciones populares.</li>
            <li>Implementa promociones para incentivar la prueba de nuevos platillos.</li>
        </ul>
    </div>

    <div class="ayuda-estadisticas">
        <h3>Platillos con mayores ventas:</h3>
        <ul>
            <li>Analiza ingredientes y métodos de preparación para replicar su éxito.</li>
            <li>Destaca estos platillos en promociones y publicidad.</li>
        </ul>
        <h3>Platillos con menores ventas:</h3>
        <ul>
            <li>Realiza promociones especiales o descuentos temporales.</li>
            <li>Revisa opiniones de clientes para identificar posibles mejoras.</li>
        </ul>
    </div>

    <div class="ayuda-estadisticas">
        <h3>Total de Ventas:</h3>
        <ul>
            <li>Evalúa el desempeño general del restaurante.</li>
            <li>Implementa estrategias de marketing durante periodos de bajas ventas.</li>
            <li>Compara las ventas con meses anteriores para identificar tendencias.</li>
        </ul>
        <h3>Promedio de Consumo por Mesa:</h3>
        <ul>
            <li>Fomenta el consumo con promociones de compra mínima.</li>
            <li>Identifica el promedio de consumo ideal para optimizar la rotación de mesas sin afectar la experiencia del cliente.</li>
        </ul>
    </div>

    <div class="ayuda-estadisticas">
        <h3>Días y horas pico:</h3>
        <ul>
            <li>Asegúrate de tener suficiente personal y stock durante estos periodos.</li>
            <li>Implementa ofertas especiales durante las horas no pico para balancear la afluencia.</li>
            <li>Planifica eventos o promociones durante periodos de menor afluencia.</li>
        </ul>
    </div>


    <div class="ayuda-estadisticas">
        <h3>Mesas más concurridas:</h3>
        <ul>
            <li>Mantén estas mesas limpias y listas para los clientes.</li>
            <li>Mejora la ubicación o presentación de las mesas menos populares.</li>
            <li>Evalúa la distribución del restaurante para maximizar eficiencia y comodidad.</li>
        </ul>
    </div>
</div>